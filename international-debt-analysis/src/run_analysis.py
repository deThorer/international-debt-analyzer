"""
End-to-end pipeline:  CSV -> clean -> SQLite -> SQL queries -> CSVs, charts, findings.

    python -m src.run_analysis                         # uses real data if present, else the sample
    python -m src.run_analysis --data data/raw/international_debt.csv
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

from src import charts
from src.cleaning import clean, report_to_markdown
from src.db import build_database, run_query

ROOT = Path(__file__).resolve().parents[1]
SQL_DIR = ROOT / "sql"
OUT_DIR = ROOT / "outputs"
REPORT_DIR = ROOT / "reports"

REAL_DATA = ROOT / "data/raw/international_debt.csv"
SAMPLE_DATA = ROOT / "data/raw/international_debt_sample.csv"


def pick_data_file(arg):
    if arg:
        return Path(arg)
    if REAL_DATA.exists():
        return REAL_DATA
    if SAMPLE_DATA.exists():
        print("!! real data not found, using the SYNTHETIC sample (numbers are not real)")
        return SAMPLE_DATA
    sys.exit("No data file. Put international_debt.csv in data/raw/ or run scripts/make_sample_data.py")


def query_title(sql_text: str) -> str:
    first = sql_text.strip().splitlines()[0]
    return first.lstrip("- ").strip()


def run_all_queries():
    results = {}
    for path in sorted(SQL_DIR.glob("[0-9][0-9]_*.sql")):
        sql = path.read_text()
        df = run_query(sql)
        results[path.stem] = (query_title(sql), df)
        df.to_csv(OUT_DIR / f"{path.stem}.csv", index=False)
    return results


def write_findings(results, data_file, is_sample):
    def get(name):
        return results[name][1]

    total = get("03_total_debt").iloc[0]
    top = get("04_top_debtors")
    leader = top.iloc[0]
    n_countries = int(get("01_distinct_countries").iloc[0, 0])
    n_indicators = len(get("02_distinct_indicators"))
    top_avg = get("05_avg_debt_by_indicator").iloc[0]
    repay = get("06_highest_principal_repayment")
    mix = get("09_creditor_mix")

    double_count_pct = 100 * (1 - total["dedup_total_million_usd"] / total["naive_total_million_usd"])

    lines = [
        "# Key findings",
        "",
        f"_Generated by `src/run_analysis.py` from `{data_file.name}`._",
        "",
    ]
    if is_sample:
        lines += ["> **Warning: these numbers come from the SYNTHETIC sample file.** "
                  "Run the pipeline on the real dataset before quoting any figure.", ""]

    lines += [
        f"- The data covers **{n_countries} countries** and **{n_indicators} debt indicators**.",
        f"- Summing every indicator gives **US$ {total['naive_total_million_usd'] / 1e6:,.2f} trillion**, "
        f"but **{double_count_pct:.0f}%** of that is double counting (parent series include their children). "
        f"The de-duplicated total is **US$ {total['dedup_total_million_usd'] / 1e6:,.2f} trillion**.",
        f"- **{leader['country_name']}** is the largest debtor: US$ {leader['naive_total_bn_usd']:,.2f} bn "
        f"(US$ {leader['dedup_total_bn_usd']:,.2f} bn de-duplicated), "
        f"followed by {top.iloc[1]['country_name']} and {top.iloc[2]['country_name']}.",
        f"- The indicator with the highest average is `{top_avg['debt_indicator']}` "
        f"({top_avg['indicator_name']}), US$ {top_avg['average_debt_million_usd']:,.0f} million on average.",
    ]
    if len(repay):
        lines.append(f"- Largest long-term principal repayment: **{repay.iloc[0]['country_name']}** "
                     f"(US$ {repay.iloc[0]['amount_bn_usd']:,.2f} bn).")
    amt = mix[mix["flow_type"] == "AMT"]
    if len(amt):
        parts = ", ".join(f"{r.creditor} {r.pct_of_long_term:.0f}%" for r in amt.itertuples())
        lines.append(f"- Long-term principal repayments by creditor: {parts}.")
    avg_top = get("05_avg_debt_by_indicator")["debt_indicator"].head(3).tolist()
    n_lt = sum(".DLXF." in c for c in avg_top)
    lines.append(f"- {n_lt} of the 3 indicators with the highest averages are long-term (DLXF) series, and "
                 "they are the only series that can be summed without double counting. "
                 "**Recommendation:** use long-term debt as the headline measure and break it down by "
                 "creditor type, instead of adding up all 25 indicators.")
    lines += ["", "See `outputs/` for every query result and `outputs/charts/` for the charts."]
    (REPORT_DIR / "findings.md").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", help="path to the input CSV")
    args = parser.parse_args()

    data_file = pick_data_file(args.data)
    is_sample = "sample" in data_file.name
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "charts").mkdir(exist_ok=True)
    REPORT_DIR.mkdir(exist_ok=True)

    raw = pd.read_csv(data_file)
    cleaned, report = clean(raw)
    (REPORT_DIR / "cleaning_report.md").write_text(report_to_markdown(report, data_file.name))
    print(f"cleaned: {report['rows_in']} -> {report['rows_out']} rows "
          f"({report['duplicates_removed']} duplicates, {report['missing_debt_removed']} missing)")

    db = build_database(cleaned)
    print(f"database: {db.relative_to(ROOT)}")

    results = run_all_queries()
    for name, (title, df) in results.items():
        print(f"\n{title}")
        print(df.head(10).to_string(index=False))

    charts.top_debtors_chart(results["04_top_debtors"][1], OUT_DIR / "charts")
    charts.creditor_mix_chart(results["09_creditor_mix"][1], OUT_DIR / "charts")
    charts.indicator_coverage_chart(results["07_most_common_indicators"][1], OUT_DIR / "charts")

    write_findings(results, data_file, is_sample)
    print("\nfindings -> reports/findings.md")


if __name__ == "__main__":
    main()
